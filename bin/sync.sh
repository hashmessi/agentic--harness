#!/usr/bin/env bash
# Distribute the harness to every agent CLI's global config.
#   bash ~/agent-harness/bin/sync.sh           install / update
#   bash ~/agent-harness/bin/sync.sh --check   report drift only (exit 1 if anything is stale)
# Env: HARNESS_TARGET_HOME overrides $HOME (used by tests).
# Files the harness does not own are backed up to <file>.pre-harness.bak before the first overwrite.
set -euo pipefail

HARNESS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
H="${HARNESS_TARGET_HOME:-$HOME}"
CHECK=0; [ "${1:-}" = "--check" ] && CHECK=1
MARK="GENERATED by ~/agent-harness/bin/sync.sh"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
DRIFT=0

native_path() { if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else printf '%s' "$1"; fi; }

# render_doc OUT — Part I (AGENTS.md) + Part II (REGULATIONS.md) with a provenance header.
render_doc() {
  { printf '<!-- %s from ~/agent-harness/AGENTS.md + REGULATIONS.md. Edit the sources, then re-run sync. -->\n\n' "$MARK"
    cat "$HARNESS/AGENTS.md"; printf '\n'; cat "$HARNESS/REGULATIONS.md"; } >"$1"
}
# render_skill SRC OUT — keep frontmatter first (required by skill loaders), marker right after it.
render_skill() {
  awk -v mark="$MARK" '
    NR == 1 && /^---/ { fm = 1; print; next }
    fm && /^---/ { print; print ""; print "<!-- " mark " from ~/agent-harness/skills. Edit the source, then re-run sync. -->"; fm = 0; next }
    { print }' "$1" >"$2"
}
skill_body() { awk 'NR == 1 && /^---/ { fm = 1; next } fm && /^---/ { fm = 0; next } !fm' "$1"; }

render_agent_claude() {
  { cat <<EOF
---
name: hostile-reviewer
description: Fresh-context adversarial reviewer. Use after implementing a change (before finalizing) to review the git diff read-only for bugs, security issues, regressions, performance problems, test gaps, and needless complexity. Pass the task description and base ref.
tools: Read, Grep, Glob, Bash
model: opus
---

<!-- $MARK from ~/agent-harness/skills/hostile-review. Edit the source, then re-run sync. -->
EOF
    skill_body "$HARNESS/skills/hostile-review/SKILL.md"; } >"$1"
}
render_agent_opencode() {
  { cat <<EOF
---
description: Fresh-context adversarial reviewer. Use after implementing a change (before finalizing) to review the git diff read-only for bugs, security issues, regressions, performance problems, test gaps, and needless complexity.
mode: subagent
tools:
  write: false
  edit: false
---

<!-- $MARK from ~/agent-harness/skills/hostile-review. Edit the source, then re-run sync. -->
EOF
    skill_body "$HARNESS/skills/hostile-review/SKILL.md"; } >"$1"
}
render_command_opencode() {
  cat >"$1" <<EOF
---
description: Run the harness workflow (inspect, plan, implement, verify, debug, hostile review, finalize) on a task
---

<!-- $MARK. Edit ~/agent-harness/skills/ship/SKILL.md, then re-run sync. -->
Load the \`ship\` skill and follow it exactly for this task:

\$ARGUMENTS
EOF
}

# place RENDERED TARGET — install (or check) one file.
place() {
  local src="$1" dst="$2"
  if [ -f "$dst" ] && cmp -s "$src" "$dst"; then return; fi
  if [ $CHECK -eq 1 ]; then echo "stale: $dst"; DRIFT=1; return; fi
  mkdir -p "$(dirname "$dst")"
  if [ -f "$dst" ] && ! grep -qF "$MARK" "$dst"; then
    local bak="$dst.pre-harness.bak"; [ -e "$bak" ] && bak="$dst.pre-harness.$(date +%Y%m%d%H%M%S).bak"
    cp "$dst" "$bak"; echo "backup: $dst -> $bak"
  fi
  cp "$src" "$dst"; echo "wrote:  $dst"
}

render_doc "$WORK/AGENTS.md"
SKILLS="$(cd "$HARNESS/skills" && ls -d */ | tr -d '/')"
for s in $SKILLS; do render_skill "$HARNESS/skills/$s/SKILL.md" "$WORK/$s.SKILL.md"; done
render_agent_claude "$WORK/agent-claude.md"
for a in scout implementer; do render_skill "$HARNESS/agents/$a.md" "$WORK/agent-$a.md"; done
render_agent_opencode "$WORK/agent-opencode.md"
render_command_opencode "$WORK/command-opencode.md"

# Global instruction files — identical content everywhere.
place "$WORK/AGENTS.md" "$H/.claude/CLAUDE.md"
place "$WORK/AGENTS.md" "$H/.config/opencode/AGENTS.md"
place "$WORK/AGENTS.md" "$H/.gemini/GEMINI.md"

# Workflow skills (Agent Skills format): Claude Code, OpenCode, Gemini/Antigravity.
for dir in .claude/skills .config/opencode/skills .gemini/skills; do
  for s in $SKILLS; do place "$WORK/$s.SKILL.md" "$H/$dir/$s/SKILL.md"; done
done

# Fresh-context reviewer subagents + OpenCode /ship command.
place "$WORK/agent-claude.md" "$H/.claude/agents/hostile-reviewer.md"
# Model-tiered Claude Code subagents (cheap scout, mid implementer); other CLIs follow §14 as instructions.
for a in scout implementer; do place "$WORK/agent-$a.md" "$H/.claude/agents/$a.md"; done
place "$WORK/agent-opencode.md" "$H/.config/opencode/agents/hostile-reviewer.md"
place "$WORK/command-opencode.md" "$H/.config/opencode/commands/ship.md"

# Claude Code Stop hook (merged into settings.json; other settings untouched).
GATE="$(native_path "$HARNESS/hooks/verify-gate.mjs")"
SETTINGS="$H/.claude/settings.json"
mkdir -p "$H/.claude"
GUARD="$(native_path "$HARNESS/hooks/guard-bash.mjs")"
RESULT="$(node - "$(native_path "$SETTINGS")" "$GATE" "$CHECK" "$GUARD" <<'EOF'
const fs = require("fs");
const [file, gate, check, guard] = process.argv.slice(2);
const text = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "{}";
let s;
try { s = JSON.parse(text); } catch (e) { console.log("error: " + file + " is not valid JSON — fix it first: " + e.message); process.exit(3); }
const want = { type: "command", command: "node", args: [gate], timeout: 60, statusMessage: "Harness verification gate" };
s.hooks ??= {};
s.hooks.Stop ??= [];
const isGate = (h) => h && h.type === "command" && Array.isArray(h.args) && h.args.some((a) => String(a).endsWith("verify-gate.mjs"));
let found = false, changed = false;
for (const group of s.hooks.Stop) {
  for (let i = 0; i < (group.hooks ?? []).length; i++) {
    if (!isGate(group.hooks[i])) continue;
    found = true;
    if (JSON.stringify(group.hooks[i]) !== JSON.stringify(want)) { group.hooks[i] = want; changed = true; }
  }
}
if (!found) { s.hooks.Stop.push({ hooks: [want] }); changed = true; }
// PreToolUse guard: ask a human before destructive shell commands.
const wantGuard = { type: "command", command: "node", args: [guard], timeout: 10, statusMessage: "Harness destructive-command guard" };
s.hooks.PreToolUse ??= [];
const isGuard = (h) => h && h.type === "command" && Array.isArray(h.args) && h.args.some((a) => String(a).endsWith("guard-bash.mjs"));
let gfound = false;
for (const group of s.hooks.PreToolUse) {
  for (let i = 0; i < (group.hooks ?? []).length; i++) {
    if (!isGuard(group.hooks[i])) continue;
    gfound = true;
    if (JSON.stringify(group.hooks[i]) !== JSON.stringify(wantGuard)) { group.hooks[i] = wantGuard; changed = true; }
  }
}
if (!gfound) { s.hooks.PreToolUse.push({ matcher: "Bash", hooks: [wantGuard] }); changed = true; }
if (!changed) { console.log("ok"); process.exit(0); }
if (check === "1") { console.log("stale"); process.exit(0); }
fs.writeFileSync(file, JSON.stringify(s, null, 2) + "\n");
console.log("wrote");
EOF
)" || { echo "$RESULT" >&2; exit 1; }
case "$RESULT" in
  stale) echo "stale: $SETTINGS (hooks)"; DRIFT=1 ;;
  wrote) echo "wrote:  $SETTINGS (Stop hook -> $GATE; PreToolUse guard -> $GUARD)" ;;
esac

# Ruflo MCP server for OpenCode (Claude Code gets it from the ruflo-core plugin). Merged into opencode.jsonc; other keys untouched.
OC="$H/.config/opencode/opencode.jsonc"
RESULT="$(node - "$(native_path "$OC")" "$CHECK" <<'EOF'
const fs = require("fs");
const [file, check] = process.argv.slice(2);
let s;
try { s = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : { $schema: "https://opencode.ai/config.json" }; }
catch (e) { console.log("error: " + file + " is not plain JSON (comments?) — add the ruflo mcp entry by hand: " + e.message); process.exit(3); }
const want = { type: "local", command: ["npx", "-y", "ruflo@latest", "mcp", "start"], enabled: true };
s.mcp ??= {};
if (JSON.stringify(s.mcp.ruflo) === JSON.stringify(want)) { console.log("ok"); process.exit(0); }
if (check === "1") { console.log("stale"); process.exit(0); }
s.mcp.ruflo = want;
fs.mkdirSync(require("path").dirname(file), { recursive: true });
fs.writeFileSync(file, JSON.stringify(s, null, 2) + "\n");
console.log("wrote");
EOF
)" || { echo "$RESULT" >&2; exit 1; }
case "$RESULT" in
  stale) echo "stale: $OC (ruflo mcp)"; DRIFT=1 ;;
  wrote) echo "wrote:  $OC (ruflo mcp)" ;;
esac

if [ $CHECK -eq 1 ]; then
  if [ $DRIFT -eq 1 ]; then echo "DRIFT: run bash ~/agent-harness/bin/sync.sh"; exit 1; fi
  echo "in sync"
else
  echo "sync complete"
fi
